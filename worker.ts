/*
  The Worker entry point (see `main` in wrangler.jsonc).

  `.open-next/worker.js` is generated by `opennextjs-cloudflare build` and
  serves the whole Next.js app. This file wraps it for one reason: Workers
  deliver cron triggers to a `scheduled` handler, not to a URL, and the stale
  order sweep is a route — GET /api/cron/expire-stale-orders. So the handler
  below makes that request, with the same bearer token Vercel Cron used to
  send, and the route itself is unchanged.
*/

// @ts-expect-error -- generated at build time, absent until then.
import handler, { DOQueueHandler } from './.open-next/worker.js';
import prismaQueryCompiler from './.cf/prisma-query-compiler.wasm';
import yoga from './.cf/yoga.wasm';

/*
  Workers will not compile WebAssembly from bytes at runtime, and Prisma and
  the invoice PDF's layout engine both try to. Importing the modules here has
  them compiled at deploy time instead; the two libraries pick them up from
  this global. scripts/cf-prepare.mjs writes the files and explains the rest.
*/
(globalThis as { __bbWasm?: Record<string, WebAssembly.Module> }).__bbWasm = {
  prisma: prismaQueryCompiler,
  yoga,
};

interface Env {
  CRON_SECRET?: string;
  /** This Worker, bound to itself, so the sweep runs as an ordinary request. */
  WORKER_SELF_REFERENCE: { fetch: (request: Request) => Promise<Response> };
}

async function expireStaleOrders(env: Env): Promise<void> {
  if (!env.CRON_SECRET) {
    console.warn('[cron] expire-stale-orders skipped: no CRON_SECRET configured');
    return;
  }

  // The host is never resolved — a service binding routes by binding, not DNS.
  const response = await env.WORKER_SELF_REFERENCE.fetch(
    new Request('https://bbtc-store.internal/api/cron/expire-stale-orders', {
      headers: { Authorization: `Bearer ${env.CRON_SECRET}` },
    }),
  );

  if (!response.ok) {
    console.error(`[cron] expire-stale-orders failed with ${response.status}`);
  }
}

const worker = {
  fetch: handler.fetch,

  async scheduled(
    _controller: unknown,
    env: Env,
    ctx: { waitUntil: (promise: Promise<unknown>) => void },
  ): Promise<void> {
    ctx.waitUntil(expireStaleOrders(env));
  },
};

export default worker;

// The revalidation queue is a Durable Object, and Workers only finds the class
// if the entry module exports it.
export { DOQueueHandler };
